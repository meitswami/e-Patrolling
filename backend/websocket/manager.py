"""WebSocket connection manager (minimal stub until dashboard WS is built)."""

from fastapi import WebSocket
from utils.logger import get_logger

logger = get_logger(__name__)


class WebSocketManager:
    """Tracks active dashboard connections."""

    def __init__(self) -> None:
        self.active_connections: list[WebSocket] = []

    async def connect(self, websocket: WebSocket) -> None:
        await websocket.accept()
        self.active_connections.append(websocket)
        logger.debug("WebSocket client connected (%s)", len(self.active_connections))

    def disconnect(self, websocket: WebSocket) -> None:
        if websocket in self.active_connections:
            self.active_connections.remove(websocket)

    async def broadcast_json(self, message: dict) -> None:
        """Send JSON to all connected clients; drop dead connections."""
        dead: list[WebSocket] = []
        for connection in self.active_connections:
            try:
                await connection.send_json(message)
            except Exception:
                dead.append(connection)
        for connection in dead:
            self.disconnect(connection)


ws_manager = WebSocketManager()
